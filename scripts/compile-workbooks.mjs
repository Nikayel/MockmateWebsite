function writeCompiledWorkbook(workbookId, compiled, sealedByTicketKey, publicDir, sealedDir) {
  const pubWbDir = join(publicDir, workbookId)
  mkdirSync(join(pubWbDir, "sprints"), { recursive: true })
  mkdirSync(join(pubWbDir, "tickets"), { recursive: true })
  writeFileSync(join(pubWbDir, "workbook.ts"), renderWorkbookModule(workbookId, compiled.summary))
  for (const sprint of compiled.sprints) {
    const nn = String(sprint.number).padStart(2, "0")
    writeFileSync(join(pubWbDir, "sprints", `sprint-${nn}.ts`), renderSprintModule(workbookId, sprint))
  }
  for (const [ticketKey, compiledTicket] of Object.entries(compiled.ticketsByKey)) {
    writeFileSync(join(pubWbDir, "tickets", `${ticketKey}.ts`), renderTicketModule(ticketKey, compiledTicket))
  }

  const sealWbDir = join(sealedDir, workbookId)
  mkdirSync(sealWbDir, { recursive: true })
  for (const [ticketKey, sealed] of Object.entries(sealedByTicketKey)) {
    writeFileSync(join(sealWbDir, `${ticketKey}.server.ts`), renderSealedTicketModule(sealed))
  }
}

function regenerateRegistries(publicDir, sealedDir) {
  const workbooks = discoverCompiledWorkbooks(publicDir)
  mkdirSync(publicDir, { recursive: true })
  mkdirSync(sealedDir, { recursive: true })
  writeFileSync(join(publicDir, "registry.ts"), renderPublicRegistry(workbooks))
  writeFileSync(join(sealedDir, "registry.server.ts"), renderSealedRegistry(workbooks))
  return workbooks.length
}

// ============================================================
// CLI
// ============================================================

function parseArgs(argv) {
  const positional = []
  const options = { publicDir: DEFAULT_PUBLIC_DIR, sealedDir: DEFAULT_SEALED_DIR }
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i]
    if (arg === "--public-dir") options.publicDir = resolvePath(process.cwd(), argv[++i])
    else if (arg === "--sealed-dir") options.sealedDir = resolvePath(process.cwd(), argv[++i])
    else positional.push(arg)
  }
  return { positional, options }
}

function discoverWorkbookDirs() {
  return listSubdirs(WORKBOOKS_DIR).filter((name) => existsSync(join(WORKBOOKS_DIR, name, "workbook.yaml")))
}

export function main(argv = process.argv.slice(2)) {
  const { positional, options } = parseArgs(argv)
  const targets =
    positional.length > 0
      ? positional.map((p) => (isAbsolute(p) ? p : resolvePath(process.cwd(), p)))
      : discoverWorkbookDirs().map((name) => join(WORKBOOKS_DIR, name))

  if (targets.length === 0) {
    console.error("No workbook directories found under workbooks/*, and none given as arguments.")
    process.exitCode = 1
    return
  }

  const results = []
  let failed = false
  for (const dir of targets) {
    try {
      const result = compileWorkbook(dir)
      results.push(result)
      console.log(`compiled ${relative(ROOT, dir)} (${result.workbookId})`)
    } catch (err) {
      failed = true
      console.error(`FAILED compiling ${relative(ROOT, dir)}:\n${err.message}`)
    }
  }

  if (failed) {
    console.error("Aborting: no output written because at least one workbook failed to compile.")
    process.exitCode = 1
    return
  }

  for (const { workbookId, compiled, sealedByTicketKey } of results) {
    writeCompiledWorkbook(workbookId, compiled, sealedByTicketKey, options.publicDir, options.sealedDir)
  }

  const count = regenerateRegistries(options.publicDir, options.sealedDir)
  console.log(`regenerated public + sealed registries (${count} workbook(s))`)
}

